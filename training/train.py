"""
FinGuard AI — Ensemble Model Training

Trains the full anomaly detection ensemble:
  1. Isolation Forest      (unsupervised)
  2. Local Outlier Factor  (unsupervised)
  3. One-Class SVM         (unsupervised)
  4. XGBoost Classifier    (supervised, on labeled synthetic anomalies)

Final risk_score = weighted average of all four scores × 100.
Saves models to models/production/ and archives the previous version.

Usage:
    python training/train.py
    python training/train.py --data-path data/synthetic_transactions.csv
"""

