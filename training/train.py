# Ensemble weights (must sum to 1.0)
WEIGHTS = {
    "isolation_forest": 0.20,
    "lof":              0.20,
    "ocsvm":            0.20,
    "xgboost":          0.40,
}

RISK_THRESHOLDS = {"LOW": 30, "MEDIUM": 65, "HIGH": 85}  # CRITICAL >= 85


# ---------------------------------------------------------------------------
# Data loading & preprocessing
# ---------------------------------------------------------------------------

def load_training_data(data_path: str) -> pd.DataFrame:
    """Load CSV generated by generate_data.py and prepare for feature extraction."""
    logger.info("Loading training data", extra={"path": data_path})
    df = pd.read_csv(data_path, low_memory=False)
    
    # Merge vendor registration date if vendors.csv exists
    vendors_path = Path(data_path).parent / "vendors.csv"
    if vendors_path.exists():
        v_df = pd.read_csv(vendors_path, low_memory=False)
        if "registration_date" in v_df.columns and "vendor_id" in v_df.columns:
            v_sub = v_df[["vendor_id", "registration_date"]].rename(
                columns={"registration_date": "vendor_registration_date"}
            )
            df = df.merge(v_sub, on="vendor_id", how="left")

    # Ensure required columns exist
    if "vendor_registration_date" not in df.columns:
        df["vendor_registration_date"] = pd.Timestamp("2020-01-01")

    if "transaction_date" not in df.columns:
        df["transaction_date"] = pd.to_datetime(
            df.get("invoice_date", df.get("payment_date", pd.Timestamp.now()))
        )

    for dcol in ["transaction_date", "vendor_registration_date", "invoice_date", "payment_date", "due_date"]:
        if dcol in df.columns:
            df[dcol] = pd.to_datetime(df[dcol], errors="coerce")

    df["vendor_registration_date"] = df["vendor_registration_date"].fillna(pd.Timestamp("2020-01-01"))
    df["transaction_date"]         = df["transaction_date"].fillna(pd.Timestamp.now())
    df["amount"]                   = pd.to_numeric(df["amount"], errors="coerce").fillna(0)
    df["is_anomaly"]               = df["is_anomaly"].fillna(False).astype(bool)

    logger.info("Data loaded", extra={"rows": len(df), "anomalies": int(df["is_anomaly"].sum())})
    return df


def prepare_features(df: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    """Run feature pipeline and return (X, y)."""
    # Merge vendor registration date if separate
    if "vendor_registration_date" not in df.columns:
        df["vendor_registration_date"] = pd.Timestamp("2020-01-01")

    features_df = extract_features(df)
    X = features_df[FEATURE_COLUMNS].values.astype(np.float32)
    y = df["is_anomaly"].astype(int).values
    return X, y


# ---------------------------------------------------------------------------
# Model training
# ---------------------------------------------------------------------------

def train_isolation_forest(X_train: np.ndarray) -> IsolationForest:
    logger.info("Training Isolation Forest")
    model = IsolationForest(
        n_estimators=200,
        contamination=0.10,
        max_features=1.0,
        random_state=42,
        n_jobs=-1,
    )
    model.fit(X_train)
    return model


def train_lof(X_train: np.ndarray) -> LocalOutlierFactor:
    logger.info("Training Local Outlier Factor")
    model = LocalOutlierFactor(
        n_neighbors=20,
        novelty=True,
        contamination=0.10,
        n_jobs=-1,
    )
    model.fit(X_train)
    return model


def train_ocsvm(X_train: np.ndarray) -> OneClassSVM:
    logger.info("Training One-Class SVM")
    # Subsample for OCSVM performance on large datasets
    sample_size = min(5_000, len(X_train))
    idx         = np.random.choice(len(X_train), sample_size, replace=False)
    model = OneClassSVM(nu=0.10, kernel="rbf", gamma="scale")
    model.fit(X_train[idx])
    return model


def train_xgboost(X_train: np.ndarray, y_train: np.ndarray) -> XGBClassifier:
    logger.info("Training XGBoost Classifier")
    scale_pos_weight = (y_train == 0).sum() / max((y_train == 1).sum(), 1)
    model = XGBClassifier(
        n_estimators=300,
        max_depth=6,
        learning_rate=0.05,
        subsample=0.8,
        colsample_bytree=0.8,
        scale_pos_weight=scale_pos_weight,
        eval_metric="logloss",
        random_state=42,
        n_jobs=-1,
        verbosity=0,
    )
    model.fit(X_train, y_train, eval_set=[(X_train, y_train)], verbose=False)
    return model


# ---------------------------------------------------------------------------
# Scoring & normalization
# ---------------------------------------------------------------------------

def normalize_scores(scores: np.ndarray) -> np.ndarray:
    """Min-max normalize an array of anomaly scores to [0, 1]."""
    scaler = MinMaxScaler()
    return scaler.fit_transform(scores.reshape(-1, 1)).flatten()


def compute_model_scores(
    models: dict,
    X: np.ndarray,
) -> dict[str, np.ndarray]:
    """Return normalized [0,1] anomaly scores from each model."""
    scores: dict[str, np.ndarray] = {}

    # IF: score_samples returns higher = more normal; negate and normalize
    if_raw           = -models["isolation_forest"].score_samples(X)
    scores["isolation_forest"] = normalize_scores(if_raw)

    # LOF: decision_function returns negative = anomaly; negate and normalize
    lof_raw          = -models["lof"].decision_function(X)
    scores["lof"]    = normalize_scores(lof_raw)

    # OCSVM: decision_function returns negative = anomaly
    ocsvm_raw        = -models["ocsvm"].decision_function(X)
    scores["ocsvm"]  = normalize_scores(ocsvm_raw)

    # XGBoost: probability of class 1 (anomaly)
    scores["xgboost"] = models["xgboost"].predict_proba(X)[:, 1]

    return scores


def ensemble_score(component_scores: dict[str, np.ndarray]) -> np.ndarray:
    """Weighted average → risk_score [0,1]."""
    return (
        WEIGHTS["isolation_forest"] * component_scores["isolation_forest"]
        + WEIGHTS["lof"]            * component_scores["lof"]
        + WEIGHTS["ocsvm"]          * component_scores["ocsvm"]
        + WEIGHTS["xgboost"]        * component_scores["xgboost"]
    )


def score_to_risk_level(score_0_100: float) -> str:
    if score_0_100 >= RISK_THRESHOLDS["HIGH"]:
        return "CRITICAL"
    elif score_0_100 >= RISK_THRESHOLDS["MEDIUM"]:
        return "HIGH"
    elif score_0_100 >= RISK_THRESHOLDS["LOW"]:
        return "MEDIUM"
    return "LOW"


# ---------------------------------------------------------------------------
# Evaluation
# ---------------------------------------------------------------------------

def evaluate(
    models: dict,
    X_test: np.ndarray,
    y_test: np.ndarray,
    version: str,
) -> dict[str, Any]:
    logger.info("Evaluating ensemble on holdout set", extra={"n_test": len(X_test)})
    component_scores = compute_model_scores(models, X_test)
    ens_scores       = ensemble_score(component_scores)
    risk_scores_100  = ens_scores * 100
    y_pred           = (ens_scores >= 0.5).astype(int)

    metrics: dict[str, Any] = {
        "version":      version,
        "precision":    round(float(precision_score(y_test, y_pred, zero_division=0)), 4),
        "recall":       round(float(recall_score(y_test, y_pred, zero_division=0)), 4),
        "f1":           round(float(f1_score(y_test, y_pred, zero_division=0)), 4),
        "roc_auc":      round(float(roc_auc_score(y_test, ens_scores)), 4),
        "n_test":       len(X_test),
        "n_flagged":    int(y_pred.sum()),
        "n_true_anomalies": int(y_test.sum()),
    }
    logger.info("Evaluation results", extra=metrics)
    print("\n" + "=" * 60)
    print(f"FinGuard AI — Ensemble Evaluation (v{version})")
    print("=" * 60)
    print(classification_report(y_test, y_pred, target_names=["Normal", "Anomaly"]))
    print(f"ROC-AUC:   {metrics['roc_auc']:.4f}")
    print(f"Precision: {metrics['precision']:.4f}")
    print(f"Recall:    {metrics['recall']:.4f}")
    print(f"F1 Score:  {metrics['f1']:.4f}")
    print("=" * 60 + "\n")

    # Save ROC curve
    try:
        import matplotlib.pyplot as plt
        from sklearn.metrics import roc_curve
        fpr, tpr, _ = roc_curve(y_test, ens_scores)
        plt.figure(figsize=(8, 6))
        plt.plot(fpr, tpr, label=f"Ensemble AUC={metrics['roc_auc']:.3f}", color="#6366f1")
        plt.plot([0, 1], [0, 1], "k--")
        plt.xlabel("False Positive Rate")
        plt.ylabel("True Positive Rate")
        plt.title("FinGuard AI — ROC Curve")
        plt.legend()
        plt.savefig(DOCS_DIR / f"roc_curve_{version}.png", dpi=150, bbox_inches="tight")
        plt.close()
        logger.info("ROC curve saved")
    except Exception as e:
        logger.warning("Could not save ROC curve", extra={"error": str(e)})

    return metrics


