def archive_production_models() -> None:
    """Move existing production models to archive with timestamp."""
    if not any(PROD_DIR.iterdir()):
        return
    ts        = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    dest      = ARCHIVE_DIR / ts
    dest.mkdir(parents=True, exist_ok=True)
    for f in PROD_DIR.iterdir():
        shutil.copy2(f, dest / f.name)
    logger.info("Previous models archived", extra={"archive_path": str(dest)})


def save_production_models(models: dict, scaler, metrics: dict, version: str) -> None:
    archive_production_models()
    joblib.dump(models["isolation_forest"], PROD_DIR / "isolation_forest.joblib")
    joblib.dump(models["lof"],              PROD_DIR / "lof.joblib")
    joblib.dump(models["ocsvm"],            PROD_DIR / "ocsvm.joblib")
    joblib.dump(models["xgboost"],          PROD_DIR / "xgboost.joblib")
    joblib.dump(scaler,                     PROD_DIR / "scaler.joblib")

    metadata = {
        "version":          version,
        "trained_at":       datetime.now(timezone.utc).isoformat(),
        "feature_columns":  FEATURE_COLUMNS,
        "weights":          WEIGHTS,
        "thresholds":       RISK_THRESHOLDS,
        "metrics":          metrics,
    }
    with open(PROD_DIR / "metadata.json", "w") as f:
        json.dump(metadata, f, indent=2)
    logger.info("Models saved to production", extra={"version": version, "path": str(PROD_DIR)})


def load_production_models() -> tuple[dict, Any, dict]:
    """Load models from production directory. Returns (models, scaler, metadata)."""
    models = {
        "isolation_forest": joblib.load(PROD_DIR / "isolation_forest.joblib"),
        "lof":              joblib.load(PROD_DIR / "lof.joblib"),
        "ocsvm":            joblib.load(PROD_DIR / "ocsvm.joblib"),
        "xgboost":          joblib.load(PROD_DIR / "xgboost.joblib"),
    }
    scaler   = joblib.load(PROD_DIR / "scaler.joblib")
    with open(PROD_DIR / "metadata.json") as f:
        metadata = json.load(f)
    return models, scaler, metadata


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main(data_path: str) -> None:
    version = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    logger.info("Starting ensemble training", extra={"version": version})

    df      = load_training_data(data_path)
    X, y    = prepare_features(df)

    # Train/test split (stratified on anomaly label)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42, stratify=y
    )
    logger.info("Data split", extra={
        "train": len(X_train), "test": len(X_test),
        "train_anomalies": int(y_train.sum()), "test_anomalies": int(y_test.sum()),
    })

    # Fit scaler on NORMAL training data only
    scaler = MinMaxScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled  = scaler.transform(X_test)

    # Train on normal data for unsupervised models
    X_normal = X_train_scaled[y_train == 0]

    models = {
        "isolation_forest": train_isolation_forest(X_normal),
        "lof":              train_lof(X_normal),
        "ocsvm":            train_ocsvm(X_normal),
        "xgboost":          train_xgboost(X_train_scaled, y_train),
    }

    metrics = evaluate(models, X_test_scaled, y_test, version)
    save_production_models(models, scaler, metrics, version)

    logger.info("Training complete", extra={"f1": metrics["f1"], "roc_auc": metrics["roc_auc"]})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="FinGuard AI model trainer")
    parser.add_argument(
        "--data-path",
        default=str(DATA_DIR / "synthetic_transactions.csv"),
        help="Path to the transactions CSV file",
    )
    args = parser.parse_args()
    main(args.data_path)
